/**
 * Write `src/main/megamud/SettingsFields.ts`: one field per MegaMUD setting,
 * named as the decompiled session struct names it (`Health.HpFull%` is
 * `Health_HpFullPct`), so a function ported from the decompile reads its
 * settings by the same names (docs/megamud/engine-port.md, 2026-10-12).
 *
 *   node --import ./scripts/lib/register.mjs scripts/gen-megamud-fields.mjs
 *
 * The file is checked against the schema by `SettingsFields.test.ts`, so a
 * schema change without a rerun fails the tests rather than drifting.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const { SETTINGS } = await import('../src/shared/megamud/schema.ts');
const { fieldName } = await import('../src/main/megamud/fieldNames.ts');

/**
 * The text of `SettingsFields.ts`. Here rather than beside `fieldName`, where
 * nothing in the TypeScript projects called it and a sweep for unreachable
 * code removed it (2026-10-16), leaving this script broken.
 */
function renderSettingsFields(defs) {
  const lines = [
    '/**',
    ' * Every MegaMUD setting as a field of the ported session, at its default.',
    ' *',
    ' * Generated by `scripts/gen-megamud-fields.mjs` from',
    ' * `src/shared/megamud/schema.ts`; do not edit. See `fieldNames.ts`.',
    ' */',
    'export class SettingsFields {'
  ];
  for (const def of defs) {
    const name = fieldName(def);
    if (!name) continue;
    const at = def.offset === undefined ? '' : ` (0x${def.offset.toString(16)})`;
    lines.push(`  /** ${def.section}.${def.key}${at} */`);
    const value =
      typeof def.default === 'string'
        ? `'${def.default.replace(/'/g, "\\'")}'`
        : String(def.default);
    const type = typeof def.default === 'string' ? 'string' : 'number';
    lines.push(`  ${name}: ${type} = ${value};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = path.join(root, 'src/main/megamud/SettingsFields.ts');
fs.writeFileSync(out, renderSettingsFields(SETTINGS));
console.log(
  `wrote ${path.relative(root, out)}: ${SETTINGS.filter((d) => fieldName(d)).length} fields`
);
